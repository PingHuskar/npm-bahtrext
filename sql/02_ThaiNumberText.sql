/* dbo.ThaiNumberText - Thai reading of an integer 0..999999 (one "million group").
   0 -> '' (empty, so callers can concatenate groups); out of range or NULL -> NULL.
   A trailing 1 is read 'เอ็ด' when the tens digit is non-zero (11 = สิบเอ็ด,
   21 = ยี่สิบเอ็ด); with @Ed = 1 it is also 'เอ็ด' after a zero tens digit
   (101 = หนึ่งร้อยเอ็ด), as with the `ed` option of function/BT.js. */
CREATE OR ALTER FUNCTION dbo.ThaiNumberText (@TheInput int, @Ed bit)
RETURNS TABLE
AS
RETURN
(
    SELECT ThaiText =
        CASE WHEN @TheInput BETWEEN 0 AND 999999
        THEN
              CASE WHEN dg.d5 > 0 THEN w.w5 + N'แสน'  ELSE N'' END
            + CASE WHEN dg.d4 > 0 THEN w.w4 + N'หมื่น' ELSE N'' END
            + CASE WHEN dg.d3 > 0 THEN w.w3 + N'พัน'   ELSE N'' END
            + CASE WHEN dg.d2 > 0 THEN w.w2 + N'ร้อย'  ELSE N'' END
            + CASE dg.d1 WHEN 0 THEN N''
                         WHEN 1 THEN N'สิบ'
                         WHEN 2 THEN N'ยี่สิบ'
                         ELSE w.w1 + N'สิบ' END
            + CASE WHEN dg.d0 = 1 AND (dg.d1 > 0 OR @Ed = 1) THEN N'เอ็ด' ELSE w.w0 END
        END
    FROM (SELECT d5 = @TheInput / 100000 % 10, d4 = @TheInput / 10000 % 10,
                 d3 = @TheInput / 1000 % 10,   d2 = @TheInput / 100 % 10,
                 d1 = @TheInput / 10 % 10,     d0 = @TheInput % 10) AS dg
    CROSS APPLY
    (SELECT
        w5 = CHOOSE(dg.d5 + 1, N'', N'หนึ่ง', N'สอง', N'สาม', N'สี่', N'ห้า', N'หก', N'เจ็ด', N'แปด', N'เก้า'),
        w4 = CHOOSE(dg.d4 + 1, N'', N'หนึ่ง', N'สอง', N'สาม', N'สี่', N'ห้า', N'หก', N'เจ็ด', N'แปด', N'เก้า'),
        w3 = CHOOSE(dg.d3 + 1, N'', N'หนึ่ง', N'สอง', N'สาม', N'สี่', N'ห้า', N'หก', N'เจ็ด', N'แปด', N'เก้า'),
        w2 = CHOOSE(dg.d2 + 1, N'', N'หนึ่ง', N'สอง', N'สาม', N'สี่', N'ห้า', N'หก', N'เจ็ด', N'แปด', N'เก้า'),
        w1 = CHOOSE(dg.d1 + 1, N'', N'หนึ่ง', N'สอง', N'สาม', N'สี่', N'ห้า', N'หก', N'เจ็ด', N'แปด', N'เก้า'),
        w0 = CHOOSE(dg.d0 + 1, N'', N'หนึ่ง', N'สอง', N'สาม', N'สี่', N'ห้า', N'หก', N'เจ็ด', N'แปด', N'เก้า')
    ) AS w
);
GO

