/* dbo.BahtText - Thai baht text for a money string (port of function/BT.js)
   @Money    cleaned like MoneyLaundering: commas / underscores / spaces / tabs /
             line breaks / non-breaking spaces removed,
             Thai digits converted, one trailing 'n' (BigInt) ignored.
   @Ed       1 = read a trailing 1 as 'เอ็ด' (e.g. 101 = หนึ่งร้อยเอ็ด)
   @Rounding '' (none: extra decimals must be zero), 'c' ceiling, 'f' floor
   Any number of integer digits (up to 4000) is read in 6-digit groups joined by
   'ล้าน', exactly like the JS library (1000001000001 = หนึ่งล้านหนึ่งล้านหนึ่ง).
   Invalid input (signs, 3+ decimals without rounding, text, ...) returns NULL;
   the JS library returns undefined or ''. Octal, binary and hexadecimal literals
   are not handled here: pass them through dbo.*ToDecimal first.
   Depends on: Tally, TrimLeadingZeros, ThaiNumberText, PrintSatangs. */
CREATE OR ALTER FUNCTION dbo.BahtText (@Money nvarchar(4000), @Ed bit, @Rounding char(1))
RETURNS TABLE
AS
RETURN
(
    SELECT Result =
        CASE WHEN ok.IsValid = 0 OR pr.Word IS NULL THEN NULL
             WHEN pr.Word = N'ถ้วน' THEN CASE WHEN b.IntText = N'' THEN N'ศูนย์' ELSE b.IntText END + N'บาทถ้วน'
             WHEN b.IntText = N'' THEN pr.Word
             ELSE b.IntText + N'บาท' + pr.Word
        END
    FROM (SELECT v0 = LTRIM(RTRIM(@Money)), r = ISNULL(RTRIM(@Rounding), '')) AS a0
    CROSS APPLY
    (SELECT v1 = TRANSLATE(REPLACE(REPLACE(REPLACE(TRANSLATE(a0.v0, NCHAR(9) + NCHAR(10) + NCHAR(11) + NCHAR(12) + NCHAR(13) + NCHAR(160), N'      '),
                                           N',', N''), N'_', N''), N' ', N''),
                           N'๐๑๒๓๔๕๖๗๘๙', N'0123456789')) AS a1
    CROSS APPLY
    (SELECT v = CASE WHEN RIGHT(a1.v1, 1) COLLATE Latin1_General_BIN2 = N'n'
                     THEN LEFT(a1.v1, LEN(a1.v1 + N'x') - 2) ELSE a1.v1 END) AS a
    CROSS APPLY
    (SELECT Dot  = CHARINDEX(N'.', a.v),
            Dots = LEN(a.v + N'x') - LEN(REPLACE(a.v, N'.', N'') + N'x')
    ) AS d
    CROSS APPLY
    (SELECT I = CASE WHEN d.Dot = 0 THEN a.v ELSE LEFT(a.v, d.Dot - 1) END,
            F = CASE WHEN d.Dot = 0 THEN N'' ELSE SUBSTRING(a.v, d.Dot + 1, 4000) END
    ) AS sp
    CROSS APPLY
    (SELECT IsValid = CASE WHEN a.v <> N''
                            AND a.v COLLATE Latin1_General_BIN2 NOT LIKE N'%[^0-9.]%'
                            AND d.Dots <= 1
                            AND LEN(a.v + N'x') - 1 - d.Dots >= 1
                            AND a0.r IN ('', 'c', 'f')
                            AND (a0.r <> '' OR SUBSTRING(sp.F, 3, 4000) NOT LIKE N'%[^0]%')
                           THEN 1 ELSE 0 END
    ) AS ok
    CROSS APPLY dbo.PrintSatangs(CAST(CASE WHEN a0.r = '' THEN LEFT(sp.F, 2) ELSE sp.F END AS varchar(8000)),
                                 a0.r) AS pr
    CROSS APPLY dbo.TrimLeadingZeros(CAST(sp.I AS varchar(8000))) AS tz
    CROSS APPLY
    (SELECT s  = tz.WithoutLeadingZeros,
            lp = PATINDEX('%[^9]%', REVERSE(tz.WithoutLeadingZeros))   -- position (from the right) of the last non-9
    ) AS n9
    CROSS APPLY
    (SELECT Int2 = CASE WHEN pr.Carry = 0 THEN n9.s
                        WHEN n9.s = '' THEN '1'
                        WHEN n9.lp = 0 THEN '1' + REPLICATE('0', LEN(n9.s))
                        ELSE LEFT(n9.s, LEN(n9.s) - n9.lp)
                           + CHAR(ASCII(SUBSTRING(n9.s, LEN(n9.s) - n9.lp + 1, 1)) + 1)
                           + REPLICATE('0', n9.lp - 1)
                   END) AS c
    CROSS APPLY
    (SELECT GC  = (LEN(c.Int2 + 'x') - 1 + 5) / 6,
            Pad = RIGHT(REPLICATE('0', 5) + c.Int2, ((LEN(c.Int2 + 'x') - 1 + 5) / 6) * 6)
    ) AS g
    CROSS APPLY
    (SELECT IntText = ISNULL((SELECT STRING_AGG(CAST(gt.Txt AS nvarchar(max)), N'') WITHIN GROUP (ORDER BY t.n)
                              FROM dbo.Tally(g.GC) AS t
                              CROSS APPLY (SELECT Grp = TRY_CAST(SUBSTRING(g.Pad, t.n * 6 + 1, 6) AS int)) AS gv
                              CROSS APPLY dbo.ThaiNumberText(gv.Grp,
                                    CASE WHEN @Ed = 1 AND NOT (t.n = 0 AND gv.Grp = 1) THEN 1 ELSE 0 END) AS tt
                              CROSS APPLY (SELECT Txt = tt.ThaiText
                                                      + CASE WHEN t.n < g.GC - 1 THEN N'ล้าน' ELSE N'' END) AS gt),
                             N'')
    ) AS b
);
GO

